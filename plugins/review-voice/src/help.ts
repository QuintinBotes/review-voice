/** The order commands are listed in; every dispatched command appears once. */
export const COMMAND_ORDER = Object.keys(COMMAND_HELP);

/** One command's help section, or null when there is no such command. */
export function commandHelp(command: string): string | null {
  return Object.hasOwn(COMMAND_HELP, command) ? COMMAND_HELP[command]!.body : null;
}

export function topLevelHelp(): string {
  // Keep at least one delimiter after the longest command name. The command
  // list is parsed by terminals and tests as well as read by people.
  const list = COMMAND_ORDER.map((name) => `  ${name.padEnd(21)}${COMMAND_HELP[name]!.summary}`);
  const reference = COMMAND_ORDER.map((name) => COMMAND_HELP[name]!.body);
  return [
    'review-voice <command>',
    '',
    'Commands:',
    ...list,
    '',
    'Options:',
    '  --version           Print the plugin version',
    '  --help              Show this message',
    '',
    'Run `review-voice <command> --help` for one command\'s flags.',
    '',
    reference.join('\n\n'),
    '',
    'Exit codes: 0 compliant, 1 violations found, 2 bad invocation.',
    '',
    'Normally driven by the /review-voice:* commands, not invoked directly.',
  ].join('\n');
}
